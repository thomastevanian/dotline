    fun rows(kind: WeatherKind): List<String> = when (kind) {
        WeatherKind.CLEAR_DAY -> sun
        WeatherKind.CLEAR_NIGHT -> moon
        WeatherKind.PARTLY_CLOUDY -> partly
        WeatherKind.CLOUDY -> cloud
        WeatherKind.FOG -> fog
        WeatherKind.DRIZZLE -> drizzle
        WeatherKind.RAIN -> rain
        WeatherKind.SNOW -> snow
        WeatherKind.THUNDER -> thunder
        WeatherKind.UNKNOWN -> unknown
    }

    fun isLit(kind: WeatherKind, row: Int, col: Int): Boolean = rows(kind)[row][col] == '#'
